"""
Скрипт для сравнения метрик похожести между вариантами сообщений.
Считает ratio по отсортированным токенам (кортеж и строка) для всех пар в группе.
"""

from __future__ import annotations

try:
    from rapidfuzz import fuzz
except ImportError:  # fallback на stdlib
    import difflib


    class _Fuzz:
        @staticmethod
        def ratio(a, b):
            return difflib.SequenceMatcher(None, a, b).ratio() * 100


    fuzz = _Fuzz()


def _strip_header(text: str) -> str:
    """
    Убираем первую строку вида "Nikita KZ, [01.12.2025 14:59]" — это не часть сообщения.
    Если строка не похожа на такую шапку, оставляем как есть.
    """
    lines = text.splitlines()
    if lines and "[" in lines[0] and "]" in lines[0]:
        lines = lines[1:]
    return "\n".join(lines)


def sorted_tokens(text: str) -> tuple[str, ...]:
    clean = _strip_header(text)
    return tuple(sorted(clean.lower().split()))


def score(a: str, b: str) -> tuple[int, int, float, float]:
    ta, tb = sorted_tokens(a), sorted_tokens(b)
    # tuple: сравнение последовательностей токенов
    s_tuple = fuzz.ratio(ta, tb)
    # str: сравнение как раньше, на склеенной строке
    s_str = fuzz.ratio(" ".join(ta), " ".join(tb))
    return len(ta), len(tb), s_tuple, s_str


def run_group(title: str, msgs: list[str]) -> None:
    print(f"--- {title} ---")
    n = len(msgs)
    for i in range(n):
        for j in range(i + 1, n):
            la, lb, st, ss = score(msgs[i], msgs[j])
            print(f"{i} vs {j}: tokens {la}/{lb}; ratio(tuple)={st:.2f}; ratio(str)={ss:.2f}")
    print()


